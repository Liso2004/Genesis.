namespace Genesis.Skill
{
    /// <summary>
    /// Represents the player's developmental relationship
    /// with a skill.
    ///
    /// Genesis skills progress through demonstrated use,
    /// not conventional character levels.
    /// </summary>
    public enum SkillMasteryStage
    {
        Exposure = 0,
        Practice = 1,
        Competence = 2,
        Confidence = 3,
        Mastery = 4,
        Innovation = 5
    }
}